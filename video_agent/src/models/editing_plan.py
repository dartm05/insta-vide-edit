"""
Editing Plan Models
Data structures for AI-generated editing decisions.
"""
from dataclasses import dataclass, field
from typing import List, Optional, Dict, Any
from enum import Enum


class TransitionType(Enum):
    """Types of video transitions."""
    CUT = "cut"
    FADE = "fade"
    DISSOLVE = "dissolve"
    WIPE = "wipe"
    SLIDE = "slide"


class ColorGrade(Enum):
    """Color grading presets."""
    NATURAL = "natural"
    VIBRANT = "vibrant"
    CINEMATIC = "cinematic"
    WARM = "warm"
    COOL = "cool"
    VINTAGE = "vintage"
    BW = "black_and_white"


@dataclass
class CropDecision:
    """Crop decision for a specific timestamp/format."""
    timestamp: float
    format_name: str
    x: int
    y: int
    width: int
    height: int
    tracking_enabled: bool = False
    subject_type: Optional[str] = None  # 'face', 'person', 'object', etc.
    confidence: float = 1.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            'timestamp': self.timestamp,
            'format': self.format_name,
            'crop_box': {
                'x': self.x,
                'y': self.y,
                'width': self.width,
                'height': self.height,
            },
            'tracking': self.tracking_enabled,
            'subject_type': self.subject_type,
            'confidence': self.confidence,
        }


@dataclass
class CutDecision:
    """Decision about which segments to keep."""
    start: float
    end: float
    score: float
    reason: str
    scene_number: Optional[int] = None
    transition_in: TransitionType = TransitionType.CUT
    transition_out: TransitionType = TransitionType.CUT

    def duration(self) -> float:
        return self.end - self.start

    def to_dict(self) -> Dict[str, Any]:
        return {
            'start': self.start,
            'end': self.end,
            'duration': self.duration(),
            'score': self.score,
            'reason': self.reason,
            'scene_number': self.scene_number,
            'transition_in': self.transition_in.value,
            'transition_out': self.transition_out.value,
        }


@dataclass
class Caption:
    """Caption/subtitle data."""
    text: str
    start: float
    end: float
    position: str = 'bottom'  # 'top', 'center', 'bottom'
    style: Optional[Dict[str, Any]] = None

    def duration(self) -> float:
        return self.end - self.start

    def to_dict(self) -> Dict[str, Any]:
        return {
            'text': self.text,
            'start': self.start,
            'end': self.end,
            'duration': self.duration(),
            'position': self.position,
            'style': self.style or {},
        }


@dataclass
class EffectSettings:
    """Visual effects and enhancements."""
    color_grade: ColorGrade = ColorGrade.NATURAL
    brightness: float = 0.0  # -1.0 to 1.0
    contrast: float = 0.0  # -1.0 to 1.0
    saturation: float = 0.0  # -1.0 to 1.0
    sharpness: float = 0.0  # 0.0 to 2.0
    vignette: float = 0.0  # 0.0 to 1.0
    music_mood: Optional[str] = None
    music_volume: float = 0.3  # 0.0 to 1.0
    apply_stabilization: bool = False
    apply_noise_reduction: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            'color_grade': self.color_grade.value,
            'brightness': self.brightness,
            'contrast': self.contrast,
            'saturation': self.saturation,
            'sharpness': self.sharpness,
            'vignette': self.vignette,
            'music_mood': self.music_mood,
            'music_volume': self.music_volume,
            'apply_stabilization': self.apply_stabilization,
            'apply_noise_reduction': self.apply_noise_reduction,
        }


@dataclass
class EditingPlan:
    """Complete editing plan generated by AI."""
    format_name: str
    crop_decisions: List[CropDecision] = field(default_factory=list)
    cuts: List[CutDecision] = field(default_factory=list)
    captions: List[Caption] = field(default_factory=list)
    effects: EffectSettings = field(default_factory=EffectSettings)
    target_duration: Optional[float] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    def get_total_duration(self) -> float:
        """Calculate total duration from cuts."""
        return sum(cut.duration() for cut in self.cuts)

    def validate(self) -> bool:
        """Validate the editing plan."""
        # Check cuts don't overlap
        sorted_cuts = sorted(self.cuts, key=lambda c: c.start)
        for i in range(len(sorted_cuts) - 1):
            if sorted_cuts[i].end > sorted_cuts[i + 1].start:
                return False

        # Check captions are within cut ranges
        for caption in self.captions:
            in_range = any(
                cut.start <= caption.start <= cut.end
                for cut in self.cuts
            )
            if not in_range:
                return False

        return True

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary."""
        return {
            'format_name': self.format_name,
            'crop_decisions': [c.to_dict() for c in self.crop_decisions],
            'cuts': [c.to_dict() for c in self.cuts],
            'captions': [c.to_dict() for c in self.captions],
            'effects': self.effects.to_dict(),
            'target_duration': self.target_duration,
            'total_duration': self.get_total_duration(),
            'metadata': self.metadata,
        }
